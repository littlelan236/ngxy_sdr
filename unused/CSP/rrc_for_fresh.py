def parser(string):
    """将matlab的输出转换为python数组格式"""
    result = []
    in_space = False

    for char in string:
        if char == " ":
            # 如果是空格且之前不在空格中
            if not in_space:
                result.append(",")
                in_space = True
        else:
            # 如果不是空格，添加字符·
            result.append(char)
            in_space = False

    return "".join(result)


