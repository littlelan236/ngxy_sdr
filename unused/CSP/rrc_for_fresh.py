def root_raised_cosine(shift, N=160000, beta=0.5, Tsym=4e-6, Fs=200e6):
    """
    Root raised cosine pulse
    """
    time_idx = np.arange(-N / 2, N / 2) / Fs
    h_rrc = np.zeros(time_idx.shape)
    for i in range(time_idx.size):
        t = time_idx[i] - shift
        if t == 0.0:
            h_rrc[i] = 1.0 - beta + (4 * beta / np.pi)
        elif beta != 0 and t == Tsym / (4 * beta):
            h_rrc[i] = (beta / np.sqrt(2)) * (
                ((1 + 2 / np.pi) * (np.sin(np.pi / (4 * beta))))
                + ((1 - 2 / np.pi) * (np.cos(np.pi / (4 * beta))))
            )
        elif beta != 0 and t == -Tsym / (4 * beta):
            h_rrc[i] = (beta / np.sqrt(2)) * (
                ((1 + 2 / np.pi) * (np.sin(np.pi / (4 * beta))))
                + ((1 - 2 / np.pi) * (np.cos(np.pi / (4 * beta))))
            )
        else:
            h_rrc[i] = (
                np.sin(np.pi * t * (1 - beta) / Tsym)
                + 4 * beta * (t / Tsym) * np.cos(np.pi * t * (1 + beta) / Tsym)
            ) / (np.pi * t * (1 - (4 * beta * t / Tsym) ** 2) / Tsym)
    return h_rrc


